-- Infastrcture and Roles

-- create a role strictly for data governance
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS GOVERNANCE_ADMIN;
GRANT ROLE GOVERNANCE_ADMIN TO ROLE ACCOUNTADMIN;

-- create our compute and storage
CREATE WAREHOUSE IF NOT EXISTS GOV_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
;

CREATE DATABASE IF NOT EXISTS ENTERPRISE_DB;
CREATE SCHEMA IF NOT EXISTS ENTERPRISE_DB.BRONZE_RAW;
CREATE SCHEMA IF NOT EXISTS ENTERPRISE_DB.SILVER_SECURE;

-- transfer schema ownership and database and warehouse usage to governance admin
GRANT OWNERSHIP ON SCHEMA ENTERPRISE_DB.SILVER_SECURE TO ROLE GOVERNANCE_ADMIN REVOKE CURRENT GRANTS;
GRANT USAGE ON DATABASE ENTERPRISE_DB TO ROLE SYSADMIN;
GRANT USAGE ON DATABASE ENTERPRISE_DB TO ROLE GOVERNANCE_ADMIN;
GRANT ALL PRIVILEGES ON SCHEMA ENTERPRISE_DB.BRONZE_RAW TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOVERNANCE_ADMIN;

-- Create Access Control Verification Hierarchy
CREATE ROLE IF NOT EXISTS DATA_ENGINEER;
CREATE ROLE IF NOT EXISTS HR_ANALYST;
CREATE ROLE IF NOT EXISTS MARKETING_ANALYST;

-- establish hierarchy
GRANT ROLE MARKETING_ANALYST TO ROLE DATA_ENGINEER;
GRANT ROLE HR_ANALYST TO ROLE DATA_ENGINEER;
GRANT ROLE DATA_ENGINEER TO ROLE  SYSADMIN;

-- grant warehouse access to consumer roles
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE HR_ANALYST;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE MARKETING_ANALYST;

