GRANT USAGE ON DATABASE ENTERPRISE_DB TO ROLE MARKETING_ANALYST;
GRANT USAGE ON SCHEMA ENTERPRISE_DB.SILVER_SECURE TO ROLE HR_ANALYST;
GRANT USAGE ON SCHEMA ENTERPRISE_DB.SILVER_SECURE TO ROLE MARKETING_ANALYST;
GRANT SELECT ON TABLE ENTERPRISE_DB.SILVER_SECURE.CUSTOMER_PROFILES TO ROLE HR_ANALYST;
GRANT SELECT ON TABLE ENTERPRISE_DB.SILVER_SECURE.CUSTOMER_PROFILES TO ROLE MARKETING_ANALYST;