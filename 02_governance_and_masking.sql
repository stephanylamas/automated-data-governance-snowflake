-- Column-Level Security (CLS), Object Tagging and Secure Target Layer

USE ROLE ACCOUNTADMIN;

GRANT CREATE TABLE, CREATE MASKING POLICY, CREATE TAG ON SCHEMA ENTERPRISE_DB.SILVER_SECURE TO ROLE GOVERNANCE_ADMIN;
GRANT ALL PRIVILEGES ON SCHEMA ENTERPRISE_DB.SILVER_SECURE TO ROLE GOVERNANCE_ADMIN;
GRANT USAGE ON DATABASE ENTERPRISE_DB TO ROLE GOVERNANCE_ADMIN;


USE ROLE GOVERNANCE_ADMIN;
USE WAREHOUSE GOV_WH;
USE DATABASE ENTERPRISE_DB;
USE SCHEMA SILVER_SECURE;

ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN EMAIL UNSET MASKING POLICY;
ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN SALARY UNSET MASKING POLICY;


-- create dynamic masking policies
CREATE OR REPLACE MASKING POLICY SILVER_SECURE.EMAIL_MASK_POLICY AS (VAL VARCHAR) RETURNS VARCHAR -> 
    CASE
        WHEN CURRENT_ROLE() IN ('GOVERNANCE_ADMIN', 'HR_ANALYST') THEN VAL
        ELSE REGEXP_REPLACE(VAL, '(^..)(.*)(@.*)', '\\1*****\\3')
    END;

CREATE OR REPLACE MASKING POLICY SILVER_SECURE.SALARY_MASK_POLICY AS (VAL NUMBER) RETURNS NUMBER ->
    CASE
        WHEN CURRENT_ROLE() IN ('GOVERNANCE_ADMIN', 'HR_ANALYST') THEN VAL
        ELSE 0
    END;

-- create classification tags
CREATE OR REPLACE TAG SILVER_SECURE.PII_CLASSIFICATION COMMENT = 'metadata tag for sensitive entities';

-- create protected production layer with bound policies
DROP TABLE IF EXISTS SILVER_SECURE.CUSTOMER_PROFILES;

CREATE TABLE SILVER_SECURE.CUSTOMER_PROFILES (
    CUSTOMER_ID VARCHAR,
    FULL_NAME VARCHAR,
    EMAIL VARCHAR,
    SALARY NUMBER,
    REGION VARCHAR
);

-- Object Tags via Explicit Governance Modifications (Alation Strategy)
ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN FULL_NAME SET TAG SILVER_SECURE.PII_CLASSIFICATION = 'NAME';
ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN EMAIL SET TAG SILVER_SECURE.PII_CLASSIFICATION = 'EMAIL';
ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN SALARY SET TAG SILVER_SECURE.PII_CLASSIFICATION = 'CONFIDENTIAL';

-- Column Masking Policies via Explicit Governance Modifications (Immuta Strategy)
ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN EMAIL SET MASKING POLICY SILVER_SECURE.EMAIL_MASK_POLICY;
ALTER TABLE SILVER_SECURE.CUSTOMER_PROFILES MODIFY COLUMN SALARY SET MASKING POLICY SILVER_SECURE.SALARY_MASK_POLICY;

-- permissions on raw landing for governance admin to access raw data
USE ROLE ACCOUNTADMIN;
GRANT USAGE ON SCHEMA ENTERPRISE_DB.BRONZE_RAW TO ROLE GOVERNANCE_ADMIN;
GRANT SELECT ON TABLE ENTERPRISE_DB.BRONZE_RAW.CUSTOMER_LANDING TO ROLE GOVERNANCE_ADMIN;

-- populate the secure target layer
USE ROLE GOVERNANCE_ADMIN;
INSERT INTO SILVER_SECURE.CUSTOMER_PROFILES SELECT * FROM ENTERPRISE_DB.BRONZE_RAW.CUSTOMER_LANDING;

